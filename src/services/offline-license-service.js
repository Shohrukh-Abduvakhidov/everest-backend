const day = 24 * 60 * 60 * 1000
const downloadUrlTtlSeconds = 15 * 60
const minimumKeySecretLength = 32
const keyVersion = 1
const deviceKeyPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/

function dependencies(overrides = {}) {
   return {
      offline: overrides.offline || offlineLicenseRepository,
      learner: overrides.learner || learnerLessonRepository,
      lessons: overrides.repository || lessonRepository,
      auth: overrides.auth || authRepository,
      transaction: overrides.transaction || withTransaction,
      storage: () => overrides.storage || getStorageProvider(),
      clock: overrides.clock || (() => new Date()),
      requireAccess: overrides.requireAccess || requireModuleAccessService,
      config: overrides.offlineConfig || env.offline,
   }
}

function iso(value) {
   return value === null || value === undefined ? null : new Date(value).toISOString()
}

function parseLicenseId(value) {
   return parseId(value, 'INVALID_LICENSE_ID', 'Offline license identifier is invalid')
}

function parseSessionId(value) {
   return parseId(value, 'INVALID_SESSION_ID', 'Session identifier is invalid')
}

function parseDeviceKey(value, field = 'deviceId') {
   if (typeof value !== 'string' || !deviceKeyPattern.test(value.toLowerCase())) {
      throw validationError(field, 'deviceId must be a UUID generated by the app')
   }
   return value.toLowerCase()
}

function optionalDeviceKey(query) {
   const value = query?.deviceId
   return value === undefined || value === '' ? null : parseDeviceKey(value)
}

function deviceNotRegistered() {
   return new AppError(409, 'OFFLINE_DEVICE_NOT_REGISTERED', 'Register this device for offline viewing first')
}

function deviceLimit(maximumDevices) {
   return new AppError(409, 'OFFLINE_DEVICE_LIMIT', `Offline viewing is limited to ${maximumDevices} devices`, [
      { maximumDevices },
   ])
}

// The content key is derived, never stored: HMAC-SHA256 over the license identity with a
// server secret gives the same 256-bit AES-GCM key for every request on that license, and a
// different key for another user, device, video or license.
function deriveContentKey(secret, { userId, deviceKey, assetId, licenseId }) {
   return createHmac('sha256', secret)
      .update(`everest-offline-key|v${keyVersion}|${userId}|${deviceKey}|${assetId}|${licenseId}`)
      .digest()
}

function requireKeySecret(deps) {
   const secret = deps.config.keySecret
   if (typeof secret !== 'string' || secret.length < minimumKeySecretLength) {
      throw new AppError(503, 'OFFLINE_KEYS_UNAVAILABLE', 'Offline viewing is not configured')
   }
   return secret
}

function encryptionFor(deps, license) {
   if (!license.device_key) return null
   const key = deriveContentKey(requireKeySecret(deps), {
      userId: license.user_id,
      deviceKey: license.device_key,
      assetId: license.asset_id,
      licenseId: license.id,
   })
   return { algorithm: 'AES-GCM', keyLength: 256, keyVersion, key: key.toString('base64url') }
}

function safeDevice(row) {
   return {
      deviceId: row.device_key,
      label: row.label,
      registeredAt: iso(row.registered_at),
      lastSeenAt: iso(row.last_seen_at),
      ...(row.active_licenses === undefined ? {} : { activeLicenses: row.active_licenses }),
   }
}

function licenseNotFound() {
   return new AppError(404, 'OFFLINE_LICENSE_NOT_FOUND', 'Offline license was not found')
}

function offlineDenied(reason) {
   return new AppError(403, 'OFFLINE_ACCESS_DENIED', 'Offline access is no longer allowed; delete the downloaded files', [
      { reason },
   ])
}

function licenseStatus(row) {
   if (row.revoked_at) return 'revoked'
   return row.is_active ? 'active' : 'expired'
}

function safeLicense(row) {
   return {
      id: row.id,
      courseId: row.course_id,
      lessonId: row.lesson_id,
      status: licenseStatus(row),
      grantedAt: iso(row.granted_at),
      renewedAt: iso(row.renewed_at),
      lastCheckedAt: iso(row.last_checked_at),
      leaseExpiresAt: iso(row.lease_expires_at),
      deviceLabel: row.device_label,
      deviceId: row.device_key || null,
      revokeReason: row.revoke_reason,
   }
}

function parseLabel(value) {
   if (value === undefined || value === null) return null
   if (typeof value !== 'string') throw validationError('deviceLabel')
   const label = value.replace(/[\p{Cc}\p{Cf}]/gu, '').trim()
   if (!label || label.length > 100) throw validationError('deviceLabel')
   return label
}

function parseIssueBody(body) {
   const value = body === undefined ? {} : body
   validateBody(value, ['deviceLabel', 'deviceId'])
   return {
      deviceLabel: parseLabel(value.deviceLabel),
      deviceKey: value.deviceId === undefined || value.deviceId === null ? null : parseDeviceKey(value.deviceId),
   }
}

// Every check that must hold for a learner to keep an offline copy. Returns the
// playable asset, or a stable reason code the PWA uses to delete its files.
async function evaluateOfflineAccess(deps, actorId, lesson) {
   if (!lesson) return { reason: 'lesson_unavailable' }
   try {
      await deps.requireAccess(actorId, lesson.module_id)
   } catch (error) {
      if (error.code === 'MODULE_ACCESS_DENIED') return { reason: 'module_access' }
      throw error
   }
   if (!lesson.allow_offline) return { reason: 'offline_not_allowed' }
   const asset = lesson.video_asset_id && await deps.lessons.findAsset(lesson.video_asset_id)
   if (!videoPlayable(asset)) return { reason: 'video_unavailable' }
   return { asset }
}

// The lease never exceeds the configured days (OFFLINE_LICENSE_DAYS), the enrollment expiry
// or the module grant expiry. Renewal online moves it forward again.
function computeLease(now, window, licenseDays) {
   const limits = [now.getTime() + licenseDays * day]
   if (window.enrollment_expires_at) limits.push(new Date(window.enrollment_expires_at).getTime())
   if (window.grant_expires_at) limits.push(new Date(window.grant_expires_at).getTime())
   return new Date(Math.min(...limits))
}

async function issueDownload(deps, asset) {
   const url = await deps.storage().presignDownload({
      key: asset.storage_key,
      expiresIn: downloadUrlTtlSeconds,
      contentType: asset.mime_type,
      fileName: asset.file_name,
      disposition: 'attachment',
   })
   return {
      url,
      expiresAt: new Date(deps.clock().getTime() + downloadUrlTtlSeconds * 1000).toISOString(),
      mimeType: asset.mime_type,
      sizeBytes: Number(asset.size_bytes),
   }
}

async function auditOffline(deps, actorId, subjectId, code, licenseId, metadata, client) {
   await deps.auth.appendAuditEvent({
      actorUserId: actorId,
      subjectUserId: subjectId,
      code,
      entityType: licenseId ? 'offline_download' : 'lesson',
      entityId: licenseId || metadata.lessonId,
      metadata,
   }, client)
}

async function issueOfflineLicenseService(userId, sessionIdValue, courseIdValue, lessonIdValue, body, overrides) {
   const deps = dependencies(overrides)
   const actorId = parseUserId(userId)
   const sessionId = parseSessionId(sessionIdValue)
   const courseId = parseCourseId(courseIdValue)
   const lessonId = parseLessonId(lessonIdValue)
   const { deviceLabel, deviceKey } = parseIssueBody(body)
   // Device licenses carry a content key; refuse before anything is written when keys
   // cannot be derived.
   if (deviceKey) requireKeySecret(deps)
   const lesson = await deps.learner.findLearnerLesson(actorId, courseId, lessonId)
   if (!lesson) throw new AppError(404, 'LESSON_NOT_FOUND', 'Lesson was not found')
   const outcome = await deps.transaction(async (client) => {
      await deps.learner.lockUser(actorId, client)
      const device = deviceKey ? await deps.offline.findDeviceForUpdate(actorId, deviceKey, client) : null
      if (deviceKey && (!device || device.revoked_at)) throw deviceNotRegistered()
      const access = await evaluateOfflineAccess(deps, actorId, lesson)
      const assetId = lesson.video_asset_id
      let existing = null
      if (assetId && device) {
         existing = await deps.offline.findDeviceLicenseForUpdate(device.id, lessonId, assetId, client)
      }
      if (assetId && !existing) {
         existing = await deps.offline.findSessionLicenseForUpdate(sessionId, lessonId, assetId, client)
      }
      const adminRevoked = existing?.revoked_at && existing.revoke_reason !== 'user_deleted'
      const reason = access.reason || (adminRevoked ? 'license_revoked' : null)
      if (reason) {
         if (existing?.is_active) {
            await deps.offline.revokeLicense(existing.id, actorId, 'access_lost', client)
         }
         await auditOffline(deps, actorId, actorId, 'lesson.offline.denied', existing?.id, {
            courseId,
            lessonId,
            reason,
         }, client)
         return { denied: reason }
      }
      const window = await deps.offline.findAccessWindow(actorId, lesson.module_id, client)
      if (!window) return { denied: 'module_access' }
      const now = deps.clock()
      const lease = computeLease(now, window, deps.config.licenseDays)
      if (lease.getTime() <= now.getTime()) return { denied: 'module_access' }
      if (device) {
         // Registration already enforced the device limit.
         await deps.offline.touchDevice(device.id, client)
      } else {
         // Session-bound (pre-device) licenses: sessions and registered devices share the limit.
         const sessions = await deps.offline.listActiveDeviceSessions(actorId, client)
         const devices = await deps.offline.countActiveDevices(actorId, client)
         if (!sessions.includes(sessionId) && sessions.length + devices >= deps.config.maxDevices) {
            throw deviceLimit(deps.config.maxDevices)
         }
      }
      let licenseId
      if (existing) {
         await deps.offline.renewLicense(existing.id, lease.toISOString(), deviceLabel, client, device?.id)
         licenseId = existing.id
      } else {
         licenseId = (await deps.offline.insertLicense({
            userId: actorId,
            sessionId,
            lessonId,
            assetId: lesson.video_asset_id,
            leaseExpiresAt: lease.toISOString(),
            deviceLabel: deviceLabel || device?.label || null,
            deviceId: device?.id,
         }, client)).id
      }
      await auditOffline(
         deps,
         actorId,
         actorId,
         existing ? 'lesson.offline.renewed' : 'lesson.offline.granted',
         licenseId,
         { courseId, lessonId, leaseExpiresAt: lease.toISOString(), device: Boolean(device) },
         client,
      )
      return { licenseId, asset: access.asset }
   })
   if (outcome.denied) throw offlineDenied(outcome.denied)
   const license = await deps.offline.findLicense(outcome.licenseId)
   return withEncryption(deps, license, {
      license: safeLicense(license),
      download: await issueDownload(deps, outcome.asset),
   })
}

function withEncryption(deps, license, data) {
   const encryption = encryptionFor(deps, license)
   return encryption ? { ...data, encryption } : data
}

// With ?deviceId= the device's licenses (any session of the user); without it the
// session-bound licenses of the current session.
async function listSessionOfflineLicensesService(userId, sessionIdValue, query, overrides) {
   const deps = dependencies(overrides)
   const actorId = parseUserId(userId)
   const sessionId = parseSessionId(sessionIdValue)
   const deviceKey = optionalDeviceKey(query)
   if (deviceKey) {
      const device = await deps.offline.findDevice(actorId, deviceKey)
      if (!device || device.revoked_at) return { licenses: [] }
      const rows = await deps.offline.listDeviceLicenses(actorId, device.id)
      return { licenses: rows.map(safeLicense) }
   }
   const rows = await deps.offline.listSessionLicenses(actorId, sessionId)
   return { licenses: rows.map(safeLicense) }
}

// A device license is used from any session of its user that presents the device id; a
// session-bound license only from the session that holds it.
async function requireOwnSessionLicense(license, actorId, sessionId, deviceKey = null) {
   if (!license || license.user_id !== actorId) throw licenseNotFound()
   if (license.device_id ? license.device_key !== deviceKey : license.session_id !== sessionId) {
      throw licenseNotFound()
   }
   return license
}

async function getOfflineLicenseDownloadService(userId, sessionIdValue, licenseIdValue, query, overrides) {
   const deps = dependencies(overrides)
   const actorId = parseUserId(userId)
   const sessionId = parseSessionId(sessionIdValue)
   const licenseId = parseLicenseId(licenseIdValue)
   const deviceKey = optionalDeviceKey(query)
   const license = await requireOwnSessionLicense(
      await deps.offline.findLicense(licenseId),
      actorId,
      sessionId,
      deviceKey,
   )
   const lesson = await deps.learner.findLearnerLesson(actorId, license.course_id, license.lesson_id)
   if (!license.is_active) {
      // A license revoked because access was lost reports the current cause, e.g.
      // video_unavailable after the lesson video was replaced.
      if (license.revoke_reason === 'access_lost') {
         const lost = await evaluateOfflineAccess(deps, actorId, lesson)
         const replaced = !lost.reason && lost.asset.id !== license.asset_id
         throw offlineDenied(lost.reason || (replaced ? 'video_unavailable' : 'license_revoked'))
      }
      throw offlineDenied(license.revoked_at ? 'license_revoked' : 'license_expired')
   }
   const access = await evaluateOfflineAccess(deps, actorId, lesson)
   const reason = access.reason
      || (access.asset.id !== license.asset_id ? 'video_unavailable' : null)
   await deps.transaction(async (client) => {
      const current = await deps.offline.findLicenseForUpdate(licenseId, client)
      if (reason) {
         if (current.is_active) await deps.offline.revokeLicense(licenseId, actorId, 'access_lost', client)
         await auditOffline(deps, actorId, actorId, 'lesson.offline.denied', licenseId, {
            courseId: license.course_id,
            lessonId: license.lesson_id,
            reason,
         }, client)
      } else {
         await deps.offline.touchLicense(licenseId, client)
      }
   })
   if (reason) throw offlineDenied(reason)
   return withEncryption(deps, license, {
      license: safeLicense(license),
      download: await issueDownload(deps, access.asset),
   })
}

async function deleteOfflineLicenseService(userId, sessionIdValue, licenseIdValue, query, overrides) {
   const deps = dependencies(overrides)
   const actorId = parseUserId(userId)
   const sessionId = parseSessionId(sessionIdValue)
   const licenseId = parseLicenseId(licenseIdValue)
   const deviceKey = optionalDeviceKey(query)
   await deps.transaction(async (client) => {
      const license = await requireOwnSessionLicense(
         await deps.offline.findLicenseForUpdate(licenseId, client),
         actorId,
         sessionId,
         deviceKey,
      )
      if (license.revoked_at) return
      await deps.offline.revokeLicense(licenseId, actorId, 'user_deleted', client)
      await auditOffline(deps, actorId, actorId, 'lesson.offline.deleted', licenseId, {
         courseId: license.course_id,
         lessonId: license.lesson_id,
      }, client)
   })
   return { license: safeLicense(await deps.offline.findLicense(licenseId)) }
}

async function listUserOfflineLicensesService(actorIdValue, userIdValue, overrides) {
   const deps = dependencies(overrides)
   parseUserId(actorIdValue)
   const rows = await deps.offline.listUserLicenses(parseUserId(userIdValue))
   return { licenses: rows.map((row) => ({ ...safeLicense(row), sessionId: row.session_id })) }
}

async function revokeOfflineLicenseService(actorIdValue, licenseIdValue, overrides) {
   const deps = dependencies(overrides)
   const actorId = parseUserId(actorIdValue)
   const licenseId = parseLicenseId(licenseIdValue)
   await deps.transaction(async (client) => {
      const license = await deps.offline.findLicenseForUpdate(licenseId, client)
      if (!license) throw licenseNotFound()
      if (license.revoked_at) return
      await deps.offline.revokeLicense(licenseId, actorId, 'admin_revoked', client)
      await auditOffline(deps, actorId, license.user_id, 'lesson.offline.revoked', licenseId, {
         courseId: license.course_id,
         lessonId: license.lesson_id,
      }, client)
   })
   return { license: safeLicense(await deps.offline.findLicense(licenseId)) }
}

// The app generates a random UUID once per installation (kept next to the encrypted files)
// and registers it here. Registering the same id again is idempotent; a new device beyond
// OFFLINE_MAX_DEVICES is refused until another one is removed.
async function registerOfflineDeviceService(userId, body, overrides) {
   const deps = dependencies(overrides)
   const actorId = parseUserId(userId)
   validateBody(body, ['deviceId', 'deviceLabel'])
   const deviceKey = parseDeviceKey(body.deviceId)
   const label = parseLabel(body.deviceLabel)
   const outcome = await deps.transaction(async (client) => {
      await deps.learner.lockUser(actorId, client)
      const existing = await deps.offline.findDeviceForUpdate(actorId, deviceKey, client)
      if (existing && !existing.revoked_at) {
         return { device: await deps.offline.activateDevice(existing.id, label, client), created: false }
      }
      const sessions = await deps.offline.listActiveDeviceSessions(actorId, client)
      const active = await deps.offline.countActiveDevices(actorId, client)
      if (active + sessions.length >= deps.config.maxDevices) throw deviceLimit(deps.config.maxDevices)
      const device = existing
         ? await deps.offline.activateDevice(existing.id, label, client)
         : await deps.offline.insertDevice({ userId: actorId, deviceKey, label }, client)
      await deps.auth.appendAuditEvent({
         actorUserId: actorId,
         subjectUserId: actorId,
         code: 'lesson.offline.device_registered',
         entityType: 'offline_device',
         entityId: device.id,
         metadata: {},
      }, client)
      return { device, created: true }
   })
   return {
      device: safeDevice(outcome.device),
      created: outcome.created,
      maximumDevices: deps.config.maxDevices,
   }
}

async function listOfflineDevicesService(userId, overrides) {
   const deps = dependencies(overrides)
   const rows = await deps.offline.listDevices(parseUserId(userId))
   return { devices: rows.map(safeDevice), maximumDevices: deps.config.maxDevices }
}

// Frees a device slot from any signed-in session; every license of that device stops.
async function removeOfflineDeviceService(userId, deviceKeyValue, overrides) {
   const deps = dependencies(overrides)
   const actorId = parseUserId(userId)
   const deviceKey = parseDeviceKey(deviceKeyValue)
   const revokedLicenses = await deps.transaction(async (client) => {
      const device = await deps.offline.findDeviceForUpdate(actorId, deviceKey, client)
      if (!device || device.revoked_at) {
         throw new AppError(404, 'OFFLINE_DEVICE_NOT_FOUND', 'Offline device was not found')
      }
      await deps.offline.revokeDevice(device.id, client)
      const count = await deps.offline.revokeDeviceLicenses(device.id, actorId, client)
      await deps.auth.appendAuditEvent({
         actorUserId: actorId,
         subjectUserId: actorId,
         code: 'lesson.offline.device_removed',
         entityType: 'offline_device',
         entityId: device.id,
         metadata: { revokedLicenses: count },
      }, client)
      return count
   })
   return { deviceId: deviceKey, status: 'removed', revokedLicenses }
}

